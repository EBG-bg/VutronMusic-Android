function copyZod(directory, prefix = '') {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const relative = prefix ? prefix + '/' + entry.name : entry.name
    const from = path.join(directory, entry.name)
    if (entry.isDirectory()) { if (relative === 'v4' || relative.startsWith('v4/')) copyZod(from, relative); continue }
    if (!entry.isFile() || !(relative.startsWith('v4/') && relative.endsWith('.cjs') || ['index.cjs', 'package.json', 'LICENSE'].includes(relative))) continue
    const original = fs.readFileSync(from, 'utf8'), converted = compatibility.transform(original, relative)
    const name = 'node_modules/zod/' + relative, destination = path.join(target, name)
    compatibility.record(compatibleFiles, name, original, converted)
    if (check) { if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== converted.code) throw new Error('Runtime Zod source differs: ' + name) }
    else { fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.writeFileSync(destination, converted.code) }
  }
}
