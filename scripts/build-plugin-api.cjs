// Preserve the upstream export list while distinguishing literal unsupported
// placeholders from real methods. Do not execute a method or infer support from
// a conditional error path, which could incorrectly hide a working operation.
function unsupportedMethods(code, fileName) {
  const source = ts.createSourceFile(fileName, code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const unwrap = node => { while (node && ts.isParenthesizedExpression(node)) node = node.expression; return node }
  const unsupported = new Set()
  function visit(node) {
    if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.EqualsToken
        && ts.isPropertyAccessExpression(node.left) && ts.isIdentifier(node.left.expression)
        && node.left.expression.text === 'exports') {
      const value = unwrap(node.right)
      if (ts.isArrowFunction(value) || ts.isFunctionExpression(value)) {
        let returned = value.body
        if (ts.isBlock(returned)) returned = returned.statements.length === 1 && ts.isReturnStatement(returned.statements[0])
          ? returned.statements[0].expression : undefined
        returned = unwrap(returned)
        if (returned && ts.isObjectLiteralExpression(returned)) {
          const codeProperty = returned.properties.find(property => ts.isPropertyAssignment(property)
            && (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) && property.name.text === 'code')
          const status = codeProperty && unwrap(codeProperty.initializer)
          if (status && ts.isNumericLiteral(status) && Number(status.text) === 404) unsupported.add(node.left.name.text)
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return [...unsupported].sort()
}
const unhandled = error => { throw error }
process.on('unhandledRejection', unhandled)
async function main() {
  const list = []
  for (const id of ids) {
    const exports = Object.create(null)
    const absent = () => Promise.resolve({})
    const api = {
      db: { get: absent, set: () => {} }, store: { get: absent, set: () => {} },
      log: () => {}, http: { get: absent, post: absent, delete: absent },
      utils: { md5: value => crypto.createHash('md5').update(value).digest('hex'), generateSalt: () => '0123456789ab', generateToken: () => '' }
    }
    const code = fs.readFileSync(path.join(target, 'plugins', id + '.js'), 'utf8')
    vm.runInNewContext(code, { api, exports, URL, URLSearchParams, Buffer, console: { log() {}, warn() {}, error() {} }, setTimeout: () => 0, clearTimeout() {} }, { timeout: 2000, filename: id + '.js' })
    await new Promise(resolve => setImmediate(resolve))
    list.push({ id, ...exports.meta, methods: Object.keys(exports).filter(key => typeof exports[key] === 'function').sort(), unsupportedMethods: unsupportedMethods(code, id + '.js'), builtIn: true, enabled: true })
  }
  emit('plugins/builtin-index.json', JSON.stringify(list, null, 2) + '\n')
  compatibility.manifest(target, 'contracts', compatibleFiles, check)
  process.removeListener('unhandledRejection', unhandled)
  console.log((check ? 'Verified' : 'Generated') + ' plugin contracts and ' + list.length + ' upstream plugin manifests')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
