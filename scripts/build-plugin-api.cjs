const compatibility = require('./runtime-regex-compat.cjs')
const compatibleFiles = []

function emit(file, contents) {
  const converted = compatibility.transform(contents, file)
  compatibility.record(compatibleFiles, file, contents, converted)
  contents = converted.code
  const destination = path.join(target, file)
  if (check) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== contents) throw new Error('Plugin contract output differs: ' + file)
  } else fs.writeFileSync(destination, contents)
}
function compile(source, output, substitutions = []) {
  let result = ts.transpileModule(fs.readFileSync(path.join(root, source), 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true }, fileName: source
  }).outputText
  for (const [from, to] of substitutions) result = result.replaceAll(from, to)
  emit(output, '// Generated by scripts/build-plugin-api.cjs from ' + source + '.\n' + result)
}
