// Real App, synthetic saved files/accounts. No external requests or device access.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')
const { expect } = require('@playwright/test')

async function main() {
  const app = path.resolve(__dirname, '..')
  const artifacts = process.env.VUTRON_TEST_ARTIFACTS || path.resolve(app, '../../_analysis/plugin-playlist-cache-browser')
  fs.mkdirSync(artifacts, { recursive:true })
  const { createServer } = await import('vite')
  const server = await createServer({ root:app,
    optimizeDeps:{ entries:['tests/fixtures/music-sources-integration.html'] },
    plugins:[{ name:'isolated-plugin-playlist-cache', enforce:'pre', transform(_code, rawId) {
      const id = rawId.replaceAll('\\', '/')
      if (id.endsWith('/src/platform/vutronPlugin.ts')) return "export { vutronPlugin } from '/tests/fixtures/music-sources-integration-native.mock.js'"
      if (id.endsWith('/src/plugins/bridge.ts')) return "export { musicPluginBridge } from '/tests/fixtures/music-sources-integration-native.mock.js'"
    } }], server:{host:'127.0.0.1',port:0}, logLevel:'error' })
  let browser, page
  const errors = []
  try {
    await server.listen()
    browser = await chromium.launch({ headless:true })
    page = await browser.newPage({ viewport:{width:320,height:720}, isMobile:true, hasTouch:true, colorScheme:'dark', locale:'en-US' })
    page.setDefaultTimeout(7500)
    page.on('pageerror', error => errors.push(error.message))
    await page.route(/^https?:\/\//, route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort('blockedbyclient'))
    await page.addInitScript(() => { localStorage.setItem('vutron:language','en'); localStorage.setItem('vutron:appearance','dark'); localStorage.setItem('vutron:font-scale','150'); localStorage.setItem('vutron:motion-preference','reduced') })
    const loaded = () => page.waitForFunction(() => window.musicSourcesReady === true)
    const sel = name => page.locator('.sidebar-toggle').click().then(() => page.locator(name).click())
    const action = page.locator('.action-dialog')
    const preview = page.locator('.plugin-library-integrated[data-integrated-section=home]')
    const popup = name => page.getByRole('button',{name:`Playlist menu for ${name}`,exact:true})
    const calls = method => page.evaluate(method => window.musicSourcesHarness.backend.calls.filter(call => call.method === method), method)
    const setOwner = scope => page.evaluate(async scope => {
      const harness=window.musicSourcesHarness
      const data=harness.backend.setAccount('fixture',scope)
      const {notifyMusicSourcesChanged}=await import('/src/plugins/useMusicSources.ts')
      notifyMusicSourcesChanged(data.plugins)
    },scope)
    await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/music-sources-integration.html'); await loaded()
    await sel('[data-music-source-id=fixture]')
    await page.locator('.bottom-nav').getByRole('button',{name:'Home',exact:true}).click()
    await expect(preview.locator('.plugin-result-card')).toHaveText(/Alpha playlist/)
    const menu = preview.getByRole('button',{name:'Playlist menu for Alpha playlist',exact:true})
    await menu.click()
    await expect(action).toContainText('only tracks marked as cached can play offline.')
    await page.keyboard.press('Escape')
    await expect(action).toHaveCount(0)
    await expect(menu).toBeFocused()
    await menu.click(); await action.getByRole('button',{name:'Save playlist',exact:true}).click()
    await expect.poll(async () => (await calls('savePluginPlaylist')).length).toBe(1)
    const saved = (await calls('savePluginPlaylist'))[0].value
    assert.equal(saved.pluginId,'fixture'); assert.equal(saved.accountScope,'alpha-account')
    assert.deepEqual(Object.keys(saved.playlist).sort(), ['id','name','picUrl','sourceContext','trackCount'])
    await expect.poll(() => page.evaluate(() => window.musicSourcesHarness.store.cachedPlaylists.find(row => row.pluginCacheKey)?.name)).toBe('Alpha playlist')
    await preview.locator('.plugin-result-card').click()
    await expect(page.locator('.plugin-detail')).toBeVisible()
    await expect(page.locator('.plugin-detail').getByRole('button',{name:'Playlist menu for Alpha playlist'})).toBeVisible()
    await page.locator('.bottom-nav').getByRole('button',{name:'Search',exact:true}).click()
    await page.locator('.plugin-library-integrated[data-integrated-section=search]').getByRole('button',{name:'Playlists',exact:true}).click()
    await page.locator('.plugin-search input').fill('fixture')
    await page.locator('.plugin-search button[type=submit]').click()
    await expect(popup('Alpha playlist')).toBeVisible()
    await sel('[data-music-source-native=offline]')
    const list = page.locator('.playlist-library')
    await expect(list.getByRole('button',{name:/^Alpha playlist/})).toContainText('Alpha library')
    await expect(list.getByRole('button',{name:/^Cached list/})).toBeVisible() // Deliberate native/snapshot numeric-ID collision.
    // Persisted library is usable after a fresh offline startup. The registry read does not execute a source.
    await page.evaluate(async () => window.musicSourcesHarness.backend.setConnected(false))
    await page.reload(); await loaded()
    await expect(list.getByRole('button',{name:/^Alpha playlist/})).toBeVisible()
    assert.equal((await calls('call')).length,0)
    await list.getByRole('button',{name:/^Alpha playlist/}).click()
    const detail = page.locator('.playlist-detail-page')
    await expect(detail).toContainText('Alpha library')
    const rows = detail.locator('.track-row')
    await expect(rows).toHaveCount(3)
    await expect(rows.nth(1)).toContainText('Audio not cached')
    await expect(rows.nth(1)).toHaveAttribute('aria-disabled','true')
    await rows.nth(1).dispatchEvent('click'); assert.equal((await calls('nativePlay')).length,0)
    await page.screenshot({ path:path.join(artifacts,'snapshot-320-dark.png') })
    await rows.nth(2).click()
    await expect.poll(async () => (await calls('nativePlay')).length).toBe(1)
    const play = (await calls('nativePlay'))[0].value
    assert.equal(play.index,1); assert.deepEqual(play.queue.map(track => track.cached),[true,true])
    assert.notEqual(play.queue[0].localEntryKey,play.queue[1].localEntryKey)
    assert.equal(play.track.id,play.queue[0].id); assert.equal(play.track.localEntryKey,play.queue[1].localEntryKey)
    assert.equal((await calls('call')).length,0)
    // Restore after a new process/view, when Continue has only the persisted bookmark.
    await page.evaluate(() => window.musicSourcesHarness.backend.checkpointPlaylist(32000))
    await page.reload(); await loaded()
    await list.getByRole('button',{name:/^Alpha playlist/}).click(); await expect(rows).toHaveCount(3)
    const resume = detail.getByRole('button',{name:/^Continue playlist/})
    await expect(resume).toContainText('0:32')
    assert.equal(await resume.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, 'The bookmark fits in the narrow large-text layout')
    await page.screenshot({ path:path.join(artifacts,'resume-320-dark.png') })
    const progressReads = (await calls('getPlaylistProgress')).length
    await page.evaluate(() => { const store = window.musicSourcesHarness.store; store.tracks = [...store.tracks] })
    await resume.click()
    await expect.poll(async () => (await calls('nativePlay')).length).toBe(1)
    const continued = (await calls('nativePlay'))[0].value
    assert.equal(continued.index,1,'Continue must use the second occurrence, even when the recording ID is identical')
    assert.equal(continued.track.localEntryKey,play.track.localEntryKey)
    assert.equal(continued.position,32000)
    assert.equal((await calls('getPlaylistProgress')).length,progressReads,'Refreshing rows in the same playlist does not reread the bookmark')
    assert.equal((await calls('call')).length,0)
    await page.locator('.collapse-player').click(); await expect(rows).toHaveCount(3)
    await setOwner('other-account')
    await expect(detail).toHaveCount(0)
    await expect(list.getByRole('button',{name:/^Alpha playlist/})).toHaveCount(0)
    await expect(list.getByRole('button',{name:/^Cached list/})).toBeVisible()
    await setOwner('alpha-account')
    await expect(list.getByRole('button',{name:/^Alpha playlist/})).toBeVisible()
    await list.getByRole('button',{name:/^Alpha playlist/}).click(); await expect(rows).toHaveCount(3)
    await detail.getByRole('button',{name:'Remove offline playlist',exact:true}).click()
    await action.getByRole('button',{name:'Remove offline playlist',exact:true}).click()
    await expect(list.getByRole('button',{name:/^Alpha playlist/})).toHaveCount(0)
    assert.equal((await calls('removePluginPlaylist')).length,1)
    await expect(list.getByRole('button',{name:/^Cached list/})).toBeVisible()
    assert.deepEqual(errors,[])
    console.log('PASS: three plugin entry points, dialog focus, offline reopen, duplicate queue resume and saved progress, account isolation, cache-only deletion')
  } catch (error) {
    if (page) await page.screenshot({path:path.join(artifacts,'failure.png')}).catch(()=>{})
    throw error
  } finally { await browser?.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
