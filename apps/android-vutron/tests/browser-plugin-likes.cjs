const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const {chromium}=require('@playwright/test')

async function main(){
 const app=path.resolve(__dirname,'..'),analysis=path.resolve(app,'../../_analysis'),cache=path.join(analysis,'vite-plugin-likes')
 const {createServer}=await import('vite')
 const server=await createServer({root:app,cacheDir:cache,optimizeDeps:{entries:['tests/fixtures/plugin-likes.html']},plugins:[{name:'likes-native-fixture',enforce:'pre',transform(code,id){if(id.replaceAll('\\','/').endsWith('/src/plugins/bridge.ts'))return "export {musicPluginBridge} from '/tests/fixtures/music-plugin-native.mock.js'"}}],server:{host:'127.0.0.1',port:0},logLevel:'error'})
 await server.listen()
 const browser=await chromium.launch(process.env.EDGE_PATH?{executablePath:process.env.EDGE_PATH,headless:true}:process.platform==='win32'?{channel:'msedge',headless:true}:{headless:true})
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(server.resolvedUrls.local[0]+'tests/fixtures/plugin-likes.html')
  await page.waitForFunction(()=>window.likeReady===true)
  const rows=page.locator('.likes-row'),buttons=page.locator('[data-plugin-like-action]')
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likelist').length),0,'Closed row menus do not start liked-list requests')
  await rows.nth(0).locator('summary').click()
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Like')
  assert.equal(await buttons.nth(0).getAttribute('aria-pressed'),'false')
  await rows.nth(1).locator('summary').click()
  await page.waitForFunction(()=>document.querySelectorAll('[data-plugin-like-action]:not(:disabled)').length===2)
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likelist').length),1,'Both menus share one account read')

  await page.evaluate(()=>{window.likeHarness.backend.holdLikeWrite=true;const button=document.querySelector('[data-plugin-like-action]');button.click();button.click()})
  await page.waitForFunction(()=>Boolean(window.likeHarness.backend.pendingLikeWrite))
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').length),1,'Double click submits one write')
  assert.equal(await buttons.nth(1).isDisabled(),true,'Shared save locks the other menu')
  await page.evaluate(()=>window.likeHarness.backend.pendingLikeWrite())
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-plugin-like-action]')).every(row=>row.textContent.trim()==='Unlike'&&row.getAttribute('aria-pressed')==='true'))

  await page.evaluate(()=>window.likeHarness.backend.setFailure('likeATrack'))
  await buttons.nth(1).click()
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.inline-error')).some(row=>row.textContent.includes('Fixture write failed')))
  assert.equal(await buttons.nth(0).getAttribute('aria-pressed'),'true','A failed write keeps the confirmed state')
  await buttons.nth(1).click()
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-plugin-like-action]')).every(row=>row.textContent.trim()==='Like'&&row.getAttribute('aria-pressed')==='false'))
  const mutation=await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').at(-1).params)
  assert.deepEqual(mutation.tracks,[{id:'track-1',opaque:{provider:'fixture',cursor:'track-1'},extra:['unchanged','track-1']}],'Writes preserve the original opaque track context')
  assert.deepEqual(mutation.playlist,{opaque:{provider:'fixture',cursor:'playlist'},extra:['unchanged','playlist']},'Writes preserve the explicitly returned liked playlist context')

  await page.evaluate(async()=>{window.likeHarness.track.value=window.likeHarness.backend.tracks[1];window.likeHarness.backend.likeReadMode='partial';await window.likeHarness.refresh()})
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Liked status unknown')
  assert.equal(await buttons.nth(0).getAttribute('aria-pressed'),null,'A partial list does not pretend an unseen track is unliked')
  await page.screenshot({path:path.join(analysis,'plugin-likes-unknown-0.4.6.png'),fullPage:false})
  const beforeCancel=await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').length)
  await buttons.nth(0).click()
  await page.locator('.action-dialog').waitFor()
  await page.keyboard.press('Escape')
  await page.locator('.action-dialog').waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').length),beforeCancel,'Cancelling unknown status sends no mutation')
  assert.equal(await buttons.nth(0).evaluate(row=>row===document.activeElement),true,'The explicit-choice dialog restores focus to its source button')
  await buttons.nth(0).click()
  await page.locator('.action-dialog').waitFor()
  await page.locator('.action-dialog [data-default-action]').click()
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-plugin-like-action]')).every(row=>row.textContent.trim()==='Unlike'))
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').at(-1).params.op),'add')
  await page.evaluate(()=>window.likeHarness.track.value=window.likeHarness.backend.tracks[2])
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Liked status unknown')
  await buttons.nth(0).click()
  await page.locator('.action-dialog .secondary-button').click()
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-plugin-like-action]')).every(row=>row.textContent.trim()==='Like'))
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.filter(row=>row.method==='likeATrack').at(-1).params.op),'del')

  await page.evaluate(()=>{window.likeHarness.track.value=window.likeHarness.backend.tracks[1];window.likeHarness.backend.likeReadMode='normal';window.likeHarness.backend.holdLikeRead=true;void window.likeHarness.refresh()})
  await page.waitForFunction(()=>Boolean(window.likeHarness.backend.pendingLikeRead))
  await page.evaluate(()=>window.likeHarness.account('fixture-account-b'))
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Like'&&!document.querySelector('[data-plugin-like-action]').disabled)
  await page.evaluate(()=>window.likeHarness.backend.pendingLikeRead())
  await page.waitForTimeout(80)
  assert.equal(await buttons.nth(0).getAttribute('aria-pressed'),'false','A delayed old-account read does not replace the new account state')
  await buttons.nth(0).click()
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Unlike')
  await page.evaluate(()=>window.likeHarness.instance())
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Like'&&!document.querySelector('[data-plugin-like-action]').disabled)
  await page.evaluate(()=>window.likeHarness.switchSource('fixture'))
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')?.textContent.trim()==='Unlike')

  await page.evaluate(()=>window.likeHarness.localOnly.value=true)
  await page.waitForFunction(()=>!document.querySelector('[data-plugin-like-action]'))
  const before=await page.evaluate(()=>window.likeHarness.backend.calls.length)
  await page.waitForTimeout(150)
  assert.equal(await page.evaluate(()=>window.likeHarness.backend.calls.length),before,'Local-only mode starts no source requests')
  await page.evaluate(()=>window.likeHarness.localOnly.value=false)
  await page.waitForFunction(()=>document.querySelector('[data-plugin-like-action]')&&!document.querySelector('[data-plugin-like-action]').disabled)
  await page.evaluate(()=>{window.likeHarness.fontScale.value=150;window.likeHarness.setLocale('en')})
  await page.setViewportSize({width:320,height:720})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Liked controls fit narrow English at 150%')
  await page.screenshot({path:path.join(analysis,'plugin-likes-0.4.6.png'),fullPage:false})
  assert.deepEqual(errors,[])
  console.log('PASS: lazy/shared liked reads, shared confirmed state, failed writes, opaque write contexts, explicit unknown operations, account/source isolation, delayed reads, offline and 320px English 150%.')
 }finally{await browser.close();await server.close();assert.equal(path.dirname(path.resolve(cache)),analysis);if(fs.existsSync(cache))fs.rmSync(cache,{recursive:true,force:true})}
}
main().catch(error=>{console.error(error);process.exitCode=1})
