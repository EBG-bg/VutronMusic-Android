const path = require('node:path'), assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const app = path.resolve(__dirname, '..')
const { chromium } = require(path.join(app, 'node_modules/playwright'))
async function main() {
 const { createServer } = await import(pathToFileURL(path.join(app, 'node_modules/vite/dist/node/index.js')).href)
 const server = await createServer({ root: app, logLevel: 'error', server: { host: '127.0.0.1', port: 0 }, plugins: [{ name: 'lazy-actions-fixture', enforce: 'pre', transform(code, id) { if (id.replaceAll('\\', '/').endsWith('/src/plugins/bridge.ts')) return "export { musicPluginBridge } from '/tests/fixtures/music-plugin-native.mock.js'" } }] })
 let browser
 try {
  await server.listen(); browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 360, height: 800 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/plugin-lazy-actions.html')
  await page.waitForFunction(() => window.lazyReady)
  await page.evaluate(() => { window.lazyHarness.visible.value = true })
  await page.getByRole('button', { name: 'All tracks', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.plugin-track').length === 80)
  assert.deepEqual(await page.locator('.plugin-library-page').evaluate(node => { const state=node.__vueParentComponent.setupState; return {sameRows:state.sortedPlaylistRows===state.library.rows.value,sortAdapterRows:state.orderSource.length} }), {sameRows:true,sortAdapterRows:0}, 'Ordinary source pages retain the original array and do not allocate playlist sort adapters')
  assert.equal(await page.locator('.plugin-shared-track-actions').count(), 0, 'Closed rows do not create action components')
  assert.equal(await page.evaluate(() => window.lazyHarness.pluginBackend.calls.filter(row => row.method === 'likelist').length), 0, 'Closed rows do not read likes')
  const first = page.locator('.plugin-track-options').first()
  await first.locator('summary').click()
  await page.waitForFunction(() => document.querySelectorAll('.plugin-shared-track-actions').length === 1)
  const firstUid = await first.locator('.plugin-shared-track-actions').evaluate(node => node.__vueParentComponent.uid)
  await first.locator('summary').click()
  assert.equal(await page.locator('.plugin-shared-track-actions').count(), 1, 'Closing retains the first prepared row')
  await first.locator('summary').click()
  assert.equal(await first.locator('.plugin-shared-track-actions').evaluate(node => node.__vueParentComponent.uid), firstUid, 'Reopening reuses the component and its action state')
  await first.getByRole('button', { name: 'Add to playlist', exact: true }).click()
  await page.waitForSelector('.plugin-add-track-panel')
  await page.evaluate(() => { window.lazyHarness.back() })
  await page.waitForSelector('.plugin-add-track-panel', { state: 'detached' })
  assert.equal(await first.getAttribute('open'), '', 'Back from the nested sheet keeps its row open')
  await page.waitForFunction(() => document.activeElement?.textContent.includes('Add to playlist'))
  await first.getByRole('button', { name: 'Comments', exact: true }).click()
  await page.waitForSelector('.plugin-comment-row')
  await page.evaluate(() => { window.lazyHarness.back() })
  await page.waitForSelector('.plugin-comments-sheet', { state: 'detached' })
  await first.getByRole('button', { name: 'Play next', exact: true }).click()
  assert.equal(await page.evaluate(() => window.lazyHarness.plays.at(-1).action), 'next')
  await first.locator('summary').click()
  await page.locator('.plugin-pagination').getByRole('button', { name: 'Show more loaded items', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.plugin-track').length === 160)
  assert.equal(await page.locator('.plugin-shared-track-actions').count(), 1, 'Adding the next 80 rows does not create their actions')
  const second = page.locator('.plugin-track-options').nth(81)
  await second.locator('summary').click()
  await page.waitForFunction(() => document.querySelectorAll('.plugin-shared-track-actions').length === 2)
  await page.evaluate(() => { window.lazyHarness.pluginBackend.plugins.find(row => row.id === 'fixture').accountScope = 'new-account' ; return window.lazyHarness.refresh() })
  await page.waitForFunction(() => document.querySelectorAll('.plugin-shared-track-actions').length === 0)
  assert.equal(await page.locator('.plugin-track-options[open]').count(), 0, 'Account refresh also closes empty shells')
  await page.waitForFunction(() => document.querySelectorAll('.plugin-track').length === 80)
  await first.evaluate(node => { node.open = true })
  await page.waitForFunction(() => document.querySelectorAll('.plugin-shared-track-actions').length === 1).catch(async error => { console.error(await page.evaluate(() => ({ open: document.querySelectorAll('.plugin-track-options[open]').length, actions: document.querySelectorAll('.plugin-shared-track-actions').length, rows: document.querySelectorAll('.plugin-track').length, error: document.querySelector('.inline-error')?.textContent, calls: window.lazyHarness.pluginBackend.calls.slice(-8) }))); throw error })
  assert.notEqual(await first.locator('.plugin-shared-track-actions').evaluate(node => node.__vueParentComponent.uid), firstUid, 'An account switch starts fresh action state')
  await page.evaluate(() => { window.lazyHarness.pluginId.value = 'optional-0' })
  await page.waitForFunction(() => document.querySelector('h2')?.textContent === 'Optional source 1')
  assert.equal(await page.locator('.plugin-shared-track-actions').count(), 0, 'A source switch discards prepared row actions')
  await page.evaluate(() => { window.lazyHarness.visible.value = false })
  assert.equal(await page.locator('.plugin-shared-track-actions').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: plugin row actions mount on first expansion; close/reopen, nested sheet back/focus, next action, 80-row append, account/source reset and unmount')
 } finally { await browser?.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
